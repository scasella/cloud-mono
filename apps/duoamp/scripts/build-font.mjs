#!/usr/bin/env node
/**
 * Compiles fonts/duopixel-glyphs.mjs into a real OpenType font.
 *   npm run build:font
 * Outputs (committed, so the app builds without running this):
 *   src/fonts/DuoPixel.otf
 *   src/fonts/duopixel-charset.ts
 *
 * Metrics: 1 font pixel = 100 units, unitsPerEm = 800 (8 pixels per em:
 * 6 cap + 1 headroom + 1 descender). A font-size of 8×P CSS px therefore
 * draws each font pixel as exactly P CSS px.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALIASES, CELL, GLYPHS } from '../fonts/duopixel-glyphs.mjs';

const require = createRequire(import.meta.url);
const opentype = require('opentype.js');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const PX = 100;
const UPM = 8 * PX;
const ASC = (CELL.capHeight + 1) * PX;
const DESC = -CELL.descent * PX;
const ADV = CELL.advance * PX;

/** Pixel rows -> merged rectangles (row runs, merged downward when aligned). */
function rects(rows) {
  const out = [];
  const open = new Map(); // "x0,x1" -> rect still growing downward
  rows.forEach((row, r) => {
    if (row.length !== CELL.width) throw new Error(`row width ${row.length} != ${CELL.width}: "${row}"`);
    const runs = [];
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let e = x;
        while (e < row.length && row[e] === '#') e++;
        runs.push([x, e]);
        x = e;
      } else x++;
    }
    const next = new Map();
    for (const [x0, x1] of runs) {
      const key = `${x0},${x1}`;
      const prev = open.get(key);
      if (prev) {
        prev.r1 = r + 1;
        next.set(key, prev);
      } else {
        const rc = { x0, x1, r0: r, r1: r + 1 };
        out.push(rc);
        next.set(key, rc);
      }
    }
    open.clear();
    for (const [k, v] of next) open.set(k, v);
  });
  return out;
}

function pathFor(rows) {
  const p = new opentype.Path();
  for (const { x0, x1, r0, r1 } of rects(rows)) {
    // Row 0 is the top of the cap height; row 5's bottom is the baseline.
    const top = (CELL.capHeight - r0) * PX;
    const bottom = (CELL.capHeight - r1) * PX;
    const l = x0 * PX;
    const rr = x1 * PX;
    // Counter-clockwise (CFF convention).
    p.moveTo(l, bottom);
    p.lineTo(rr, bottom);
    p.lineTo(rr, top);
    p.lineTo(l, top);
    p.close();
  }
  return p;
}

const unicodeMap = new Map(); // char -> Set<codepoint>
for (const ch of Object.keys(GLYPHS)) {
  const set = new Set([ch.codePointAt(0)]);
  const lower = ch.toLowerCase();
  if (lower !== ch) set.add(lower.codePointAt(0));
  unicodeMap.set(ch, set);
}
// Accented Latin: map to the base letter.
for (let cp = 0xc0; cp <= 0x24f; cp++) {
  const c = String.fromCodePoint(cp);
  const base = c.normalize('NFD')[0].toUpperCase();
  if (base !== c && unicodeMap.has(base) && /[A-Z]/.test(base)) unicodeMap.get(base).add(cp);
}
for (const [from, to] of Object.entries(ALIASES)) unicodeMap.get(to)?.add(from.codePointAt(0));

const notdef = new opentype.Glyph({
  name: '.notdef',
  unicode: undefined,
  advanceWidth: ADV,
  path: pathFor(GLYPHS['?']),
});
const glyphs = [notdef];
const names = { ' ': 'space', '.': 'period', ',': 'comma', ':': 'colon', ';': 'semicolon', '-': 'hyphen' };
for (const [ch, rows] of Object.entries(GLYPHS)) {
  const cps = [...unicodeMap.get(ch)];
  const g = new opentype.Glyph({
    name: names[ch] ?? (/[A-Za-z0-9]/.test(ch) ? ch : `uni${ch.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')}`),
    unicode: cps[0],
    unicodes: cps,
    advanceWidth: ADV,
    path: pathFor(rows),
  });
  // opentype.js 1.3 ignores options.unicodes (operator-precedence bug), so set it here.
  g.unicodes = cps;
  glyphs.push(g);
}

const font = new opentype.Font({
  familyName: 'DuoPixel',
  styleName: 'Regular',
  unitsPerEm: UPM,
  ascender: ASC,
  descender: DESC,
  designer: 'DuoAmp project',
  description: 'Original 5x6 capitals bitmap face drawn for DuoAmp.',
  version: '1.0',
  glyphs,
});
mkdirSync(join(root, 'src/fonts'), { recursive: true });
const otf = Buffer.from(font.toArrayBuffer());
writeFileSync(join(root, 'src/fonts/DuoPixel.otf'), otf);

const all = [...unicodeMap.values()].flatMap((s) => [...s]).sort((a, b) => a - b);
const charset = String.fromCodePoint(...all);
writeFileSync(
  join(root, 'src/fonts/duopixel-charset.ts'),
  `// Generated by scripts/build-font.mjs - do not edit.\n` +
    `/** Every code point DuoPixel draws (capitals, lowercase -> capitals, accented Latin -> base letter, aliases). */\n` +
    `export const DUOPIXEL_CHARSET = ${JSON.stringify(charset)};\n` +
    `/** Advance in font pixels; the face is monospaced. */\n` +
    `export const DUOPIXEL_ADVANCE = ${CELL.advance};\n` +
    `/** Font pixels per em (font-size = PX_PER_EM x pixel size). */\n` +
    `export const DUOPIXEL_PX_PER_EM = ${UPM / PX};\n`,
);
console.log(`DuoPixel.otf: ${glyphs.length} glyphs, ${all.length} code points, ${otf.length} bytes`);
